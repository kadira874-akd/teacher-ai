// Fungsi untuk generate deskripsi Pancasila
export function generateDeskripsiPancasila(namaSiswa, dimensi, predikat) {
  if (!predikat || predikat === '') {
    return 'Belum dinilai.';
  }

  const dimensiTemplates = templatePancasila[dimensi];
  if (!dimensiTemplates) {
    return 'Template tidak ditemukan.';
  }

  const kalimatList = dimensiTemplates[predikat];
  if (!kalimatList || kalimatList.length === 0) {
    return 'Belum ada deskripsi untuk predikat ini.';
  }

  // Pilih kalimat secara acak
  const randomIndex = Math.floor(Math.random() * kalimatList.length);
  const template = kalimatList[randomIndex];

  // Ganti placeholder {nama} dengan nama siswa
  return template.replace('{nama}', namaSiswa);
}

// Fungsi untuk mendapatkan label predikat Pancasila
export function getPredikatPancasilaLabel(predikat) {
  const labels = {
    SB: 'Sangat Berkembang',
    BSH: 'Berkembang Sesuai Harapan',
    BB: 'Berkembang',
    MB: 'Mulai Berkembang',
  };
  return labels[predikat] || predikat;
}